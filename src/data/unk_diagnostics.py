"""Phase 2 diagnostic — what are the UNK (unmatched) messages in validation and test?

Loads the frozen Drain3 miner, re-reads the raw messages of the validation and test
periods, masks and matches them, and lists the most frequent UNMATCHED masked messages.
This separates two very different situations:
  * genuinely NEW message types after the training cut (log evolution — a finding), vs
  * masking/matching failures on messages that also exist in training (a bug to fix).

Writes results/unk_diagnostics.md.   Usage: python -m src.data.unk_diagnostics [--sample] [--top 40]
"""
from __future__ import annotations

import argparse
import pickle
from collections import Counter

import pandas as pd
import pyarrow.parquet as pq

from src.data.splits import load_split
from src.data.templates import mask
from src.utils.paths import DATA_INTERIM, DATA_SPLITS, RESULTS


def main() -> None:
    ap = argparse.ArgumentParser(); ap.add_argument("--sample", action="store_true"); ap.add_argument("--top", type=int, default=40)
    ap.add_argument("--split", default="split_v1"); args = ap.parse_args(); sfx = "_sample" if args.sample else ""
    split = load_split(DATA_SPLITS / f"{args.split}{sfx}.json")
    state = pickle.load((DATA_INTERIM / f"drain_miner{sfx}.pkl").open("rb")); miner = state["miner"]
    pf = pq.ParquetFile(DATA_INTERIM / f"bgl_parsed{sfx}.parquet")
    unk = {"validation": Counter(), "test": Counter()}; tot = {"validation": 0, "test": 0}
    matched_in_train_vocab: Counter = Counter()
    cache: dict[str, bool] = {}
    for b in pf.iter_batches(columns=["timestamp", "message", "alert_tag", "component"], batch_size=500_000):
        df = b.to_pandas(); ts = pd.to_datetime(df["timestamp"], utc=True)
        for k in ("validation", "test"):
            g = df[(ts >= split[k]["start"]) & (ts < split[k]["end"])]
            if g.empty: continue
            tot[k] += len(g)
            masked = g["message"].map(mask)
            vc = masked.value_counts()
            for m, c in vc.items():
                ok = cache.get(m)
                if ok is None:
                    ok = miner.match(m, full_search_strategy="fallback") is not None; cache[m] = ok
                if not ok: unk[k][m] += int(c)
    L = ["# UNK diagnostics (auto-generated by src/data/unk_diagnostics.py)\n",
         f"Miner fitted before {state['fitted_before']}; {len(miner.drain.clusters)} templates.\n"]
    for k in ("validation", "test"):
        n_unk = sum(unk[k].values()); n_types = len(unk[k])
        L.append(f"## {k}: {n_unk:,} / {tot[k]:,} lines unmatched ({n_unk / max(tot[k], 1):.1%}), {n_types:,} distinct unmatched masked messages\n")
        L.append("| share of UNK | lines | masked message |"); L.append("|---:|---:|---|")
        for m, c in unk[k].most_common(args.top):
            safe = m[:150].replace("|", "/")
            L.append(f"| {c / max(n_unk, 1):.1%} | {c:,} | `{safe}` |")
        L.append("")
    (RESULTS / f"unk_diagnostics{sfx}.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L[:3])); print(f"[unk] → {RESULTS / f'unk_diagnostics{sfx}.md'}")


if __name__ == "__main__":
    main()
