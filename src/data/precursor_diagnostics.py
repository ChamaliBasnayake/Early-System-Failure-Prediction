"""Phase 2 diagnostic — is there any log content BEFORE failures, and at which hardware level?

For every target episode (start s) and lead time N, count the lines written in [s-N-W, s-N] by
  node | node card (32 nodes) | midplane (512 nodes) | rack | whole system
and compare with the same units at RANDOM times (uniform over the unit's split period).
Reports, per level and W: share of pre-failure windows that are non-empty, median lines,
and the same for random windows. This decides the UNIT OF PREDICTION.
Writes results/precursor_diagnostics.md.   Usage: python -m src.data.precursor_diagnostics [--sample]
"""
from __future__ import annotations

import argparse

import numpy as np
import pandas as pd

from src.data.splits import load_split
from src.utils.paths import DATA_INTERIM, DATA_SPLITS, RESULTS

SEC = np.int64(1_000_000_000)
LEVELS = {"node": 4, "nodecard": 3, "midplane": 2, "rack": 1}


def unit_of(node: pd.Series, level: str) -> pd.Series:
    """Map a node id R02-M1-N0-C:J12-U11 to its unit at the given level."""
    node = node.astype(str)
    if level == "system":
        return pd.Series(["SYSTEM"] * len(node), index=node.index)
    if level == "node":
        return node
    k = LEVELS[level]
    parts = node.str.split("-", n=k, expand=True).iloc[:, :k]
    out = parts.iloc[:, 0].astype(str)
    for i in range(1, parts.shape[1]):
        out = out.str.cat(parts.iloc[:, i].fillna(""), sep="-")
    return out.str.rstrip("-")          # vectorised; nodes with fewer parts (e.g. UNKNOWN_LOCATION) keep their name


def counts_before(unit_times: dict[str, np.ndarray], units: np.ndarray, ends: np.ndarray, W: np.int64) -> np.ndarray:
    out = np.zeros(len(units), dtype=np.int64)
    for i, (u, e) in enumerate(zip(units, ends)):
        arr = unit_times.get(u)
        if arr is None: continue
        out[i] = np.searchsorted(arr, e, side="right") - np.searchsorted(arr, e - W, side="left")
    return out


def main() -> None:
    ap = argparse.ArgumentParser(); ap.add_argument("--sample", action="store_true"); ap.add_argument("--N", type=int, default=5)
    ap.add_argument("--n_random", type=int, default=3000); args = ap.parse_args(); sfx = "_sample" if args.sample else ""
    rng = np.random.default_rng(11)
    ev = pd.read_parquet(DATA_INTERIM / f"events{sfx}.parquet", columns=["timestamp", "node"])
    ev_t = pd.to_datetime(ev["timestamp"], utc=True).values.astype("datetime64[ns]").astype(np.int64)
    ep = pd.read_parquet(DATA_INTERIM / f"failure_episodes{sfx}.parquet")
    s_ns = pd.to_datetime(ep["start"], utc=True).values.astype("datetime64[ns]").astype(np.int64)
    split = load_split(DATA_SPLITS / f"split_v1{sfx}.json")
    t0 = pd.Timestamp(split["train"]["start"]).value; t1 = pd.Timestamp(split["test"]["end"]).value
    N = args.N * 60 * SEC
    L = ["# Precursor diagnostics (auto-generated by src/data/precursor_diagnostics.py)\n",
         f"Lead time N={args.N} min. For each level: lines in [s-N-W, s-N] before each of the {len(ep):,} target episodes vs. "
         f"{args.n_random:,} random (unit, time) draws.\n",
         "| level | W (min) | pre-failure: share non-empty | pre-failure: median lines | pre-failure: 90th pct | random: share non-empty | random: median lines | random: 90th pct | units |",
         "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for level in ["node", "nodecard", "midplane", "rack", "system"]:
        ev_u = unit_of(ev["node"], level).values
        ep_u = unit_of(ep["node"], level).values
        order = np.argsort(ev_u, kind="stable")
        us, first = np.unique(ev_u[order], return_index=True); last = np.r_[first[1:], len(order)]
        unit_times = {u: np.sort(ev_t[order[a:b]]) for u, a, b in zip(us, first, last)}
        all_units = np.array(list(unit_times.keys()))
        for Wm in (10, 60):
            W = Wm * 60 * SEC
            pre = counts_before(unit_times, ep_u, s_ns - N, W)
            ru = rng.choice(all_units, size=args.n_random); rt = rng.integers(t0 + W, t1, size=args.n_random)
            rnd = counts_before(unit_times, ru, rt, W)
            L.append(f"| {level} | {Wm} | {(pre > 0).mean():.1%} | {np.median(pre):.0f} | {np.percentile(pre, 90):.0f} | "
                     f"{(rnd > 0).mean():.1%} | {np.median(rnd):.0f} | {np.percentile(rnd, 90):.0f} | {len(all_units):,} |")
        print(f"  {level}: done")
    L.append("\nReading guide: a usable unit has pre-failure windows that are mostly NON-EMPTY and whose line counts differ from "
             "random windows of the same unit. If only 'system' is non-empty, the signal (if any) is system-wide, not local.")
    (RESULTS / f"precursor_diagnostics{sfx}.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L)); print(f"[precursor] → {RESULTS / f'precursor_diagnostics{sfx}.md'}")


if __name__ == "__main__":
    main()
