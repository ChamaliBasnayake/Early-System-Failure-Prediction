"""Phase 1, step 4b — evidence for the failure-set decision.

Usage:
    python -m src.data.explore_categories                 # full data
    python -m src.data.explore_categories --top 5
"""
from __future__ import annotations

import argparse

import pandas as pd

from src.utils.paths import DATA_INTERIM, RESULTS


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--top", type=int, default=3)
    ap.add_argument("--incident_gap", type=int, default=300, help="seconds; same-category events closer than this (system-wide) are one incident")
    ap.add_argument("--sample", action="store_true")
    args = ap.parse_args()
    suffix = "_sample" if args.sample else ""
    df = pd.read_parquet(DATA_INTERIM / f"bgl_parsed{suffix}.parquet",
                         columns=["timestamp", "node", "alert_tag", "component", "level", "message", "is_alert"])
    al = df[df.is_alert].copy()
    al["timestamp"] = pd.to_datetime(al["timestamp"], utc=True)
    al["minute"] = al["timestamp"].dt.floor("1min")

    out = ["# Alert category evidence (Generated by src.data.explore_categories.py)\n",
           f"Incident gap: {args.incident_gap} s (same category, anywhere in the system)\n"]
    rows = []
    for cat, g in al.groupby("alert_tag", sort=False):
        g = g.sort_values("timestamp")
        # incidents: new incident when the gap to the previous event of this category (any node) exceeds incident_gap
        gaps = g["timestamp"].diff().dt.total_seconds()
        n_incidents = int((gaps.isna() | (gaps > args.incident_gap)).sum())
        nodes_per_minute = g.groupby("minute")["node"].nunique()
        rows.append(dict(category=cat, component=g.component.iloc[0], lines=len(g), nodes=g.node.nunique(),
                         incidents=n_incidents, median_nodes_per_minute=float(nodes_per_minute.median()),
                         max_nodes_per_minute=int(nodes_per_minute.max())))
        top = g["message"].value_counts().head(args.top)
        out.append(f"## {cat}  ({g.component.iloc[0]}, {len(g):,} lines, {g.node.nunique():,} nodes, ~{n_incidents:,} incidents)\n")
        for m, c in top.items():
            out.append(f"- `{m[:160]}` — {c:,}")
        out.append("")
    summary = pd.DataFrame(rows).sort_values("incidents", ascending=False)
    summary.to_csv(RESULTS / f"category_evidence{suffix}.csv", index=False)
    print(summary.to_string(index=False))
    print(f"\n[explore] CSV → {RESULTS / f'category_evidence{suffix}.csv'}")


if __name__ == "__main__":
    main()
