"""Phase 5 — turn the experiment log and the curve files into the Q3.b tables and figures.

Reads experiments/log.csv (phase 4 + 5 neural rows) and results/curves/<run_id>.json; writes
results/optimisation_study.md and results/figures/study_*.png. Groups runs by the study they belong to
(learning rate, batch size, depth/width, regularisation, optimiser, class weighting, window length, architecture).
Usage: python -m src.models.study_summary
"""
from __future__ import annotations

import csv
import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from src.utils.paths import RESULTS
from src.utils.runlog import LOG_PATH

STUDIES = {
    "learning rate": ["lstm_v1_N5_s11", "lr_1e-4_N5_s11", "lr_3e-4_N5_s11", "lr_3e-3_N5_s11", "lr_1e-2_N5_s11"],
    "batch size": ["bs_32_N5_s11", "lstm_v1_N5_s11", "bs_512_N5_s11"],
    "depth / width / pooling": ["hidden_32_N5_s11", "lstm_v1_N5_s11", "hidden_128_N5_s11", "layers_2_N5_s11", "pool_meanmax_N5_s11"],
    "regularisation / normalisation": ["drop_0.1_N5_s11", "lstm_v1_N5_s11", "drop_0.5_N5_s11", "no_layernorm_N5_s11"],
    "optimiser": ["lstm_v1_N5_s11", "sgd_0.01_N5_s11", "sgd_0.1_N5_s11", "adamw_wd1e-2_N5_s11"],
    "class weighting": ["posw_1_N5_s11", "lstm_v1_N5_s11", "posw_ratio_N5_s11"],
    "local window length": ["lstm_v1_N5_s11", "w6h_w6h_N5_s11", "w24h_w24h_N5_s11"],
    "architecture": ["lstm_v1_N5_s11", "cnn_v1_N5_s11", "sem_v1_N5_s11"],
    "seeds (v1)": ["lstm_v1_N5_s11", "lstm_v1_N5_s22", "lstm_v1_N5_s33"],
}


def load_rows() -> pd.DataFrame:
    rows = list(csv.DictReader(LOG_PATH.open(encoding="utf-8")))
    df = pd.DataFrame(rows); df = df[df["phase"].isin(["4", "5"])].copy()
    for c in ("val_pr_auc", "val_recall_at_far", "val_f1", "train_time_s", "infer_ms_per_window"): df[c] = pd.to_numeric(df[c], errors="coerce")
    return df.drop_duplicates("run_id", keep="last").set_index("run_id")


def curve(run_id: str):
    p = RESULTS / "curves" / f"{run_id}.json"
    return json.loads(p.read_text()) if p.exists() else None


def main() -> None:
    df = load_rows(); L = ["# Optimisation study (Question 3.b) — auto-generated by src/models/study_summary.py\n",
                          "All runs: N = 5 min, seed 11 unless stated, selected/evaluated on VALIDATION only. Reference = lstm_v1 (Adam 1e-3, batch 128, 1×64, dropout 0.3, LayerNorm, last-state pooling, pos_weight √ratio, 60-min local window).\n"]
    (RESULTS / "figures").mkdir(exist_ok=True)
    for study, runs in STUDIES.items():
        rows = []
        for r in runs:
            c = curve(r); logrow = df.loc[r] if r in df.index else None
            if c is None and logrow is None: rows.append({"run": r, "status": "not run yet"}); continue
            best = c["best"] if c else {}
            best_ep = max(c["curves"], key=lambda x: x["val_pr_auc"])["epoch"] if c else None
            rows.append({"run": r, "changed": logrow["changed_vs_previous"] if logrow is not None else "", "val PR-AUC": round(best.get("pr_auc", float("nan")), 4),
                         "ROC": round(best.get("roc_auc", float("nan")), 3), "recall@1%FAR": round(best.get("recall@far0.01", float("nan")), 3),
                         "best epoch / trained": f"{best_ep}/{len(c['curves'])}" if c else "", "min val loss": round(min(x["val_loss"] for x in c["curves"]), 4) if c else None,
                         "train s": round(float(logrow["train_time_s"]), 0) if logrow is not None else None, "status": "ok"})
        L.append(f"## {study}\n"); L.append(pd.DataFrame(rows).to_markdown(index=False) + "\n")
        # figure: validation PR-AUC curves overlay for this study
        fig, ax = plt.subplots(1, 2, figsize=(11, 3.6)); drew = False
        for r in runs:
            c = curve(r)
            if c is None: continue
            ep = [x["epoch"] for x in c["curves"]]; drew = True
            ax[0].plot(ep, [x["val_loss"] for x in c["curves"]], label=r); ax[1].plot(ep, [x["val_pr_auc"] for x in c["curves"]], "-o", ms=2.5, label=r)
        if drew:
            ax[0].set_title(f"{study}: validation loss"); ax[1].set_title(f"{study}: validation PR-AUC"); ax[0].set_xlabel("epoch"); ax[1].set_xlabel("epoch"); ax[1].legend(fontsize=7)
            fig.tight_layout(); fn = "study_" + study.replace(" / ", "_").replace(" ", "_").replace("(", "").replace(")", "") + ".png"; fig.savefig(RESULTS / "figures" / fn, dpi=140)
            L.append(f"![]({'figures/' + fn})\n")
        plt.close(fig)
    L.append("## Notes to write (by hand, from the evidence above)\n- For each study: what moved, by how much relative to the seed spread of v1 (±0.012), and the mechanism.\n"
             "- Optimisers: relate Adam vs SGD vs AdamW behaviour to adaptive step sizes, momentum and decoupled weight decay.\n"
             "- Failed/degraded runs (expected: lr 1e-2, pos_weight ratio, possibly layers_2/hidden_128 over-fitting): diagnose from the curves.\n"
             "- Choose the final configuration and justify; then run it for 3 seeds and all N.")
    (RESULTS / "optimisation_study.md").write_text("\n".join(L), encoding="utf-8"); print(f"[study] → {RESULTS / 'optimisation_study.md'}")


if __name__ == "__main__":
    main()
