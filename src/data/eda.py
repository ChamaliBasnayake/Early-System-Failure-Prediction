"""Phase 1, step 3 — exploratory data analysis for Question 1.

Usage:
    python -m src.data.eda              # uses data/interim/bgl_parsed.parquet
    python -m src.data.eda --sample     # uses the sample parquet
"""
from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from src.utils.paths import DATA_INTERIM, RESULTS

FIG = RESULTS / "figures"


SUFFIX = ""


def _save(fig: plt.Figure, name: str) -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    fig.tight_layout()
    stem, ext = name.rsplit(".", 1)
    fig.savefig(FIG / f"{stem}{SUFFIX}.{ext}", dpi=150)
    plt.close(fig)


def run(parquet: Path) -> None:
    df = pd.read_parquet(parquet)
    df["timestamp"] = pd.to_datetime(df["timestamp"], utc=True)
    df = df.sort_values("timestamp").reset_index(drop=True)
    lines = []
    add = lines.append

    add("# EDA summary (Generated by src/data/eda.py)\n")
    add(f"Source parquet: `{parquet}`\n")
    add(f"- Rows: **{len(df):,}**")
    add(f"- Time span: **{df.timestamp.min()} → {df.timestamp.max()}** "
        f"({(df.timestamp.max() - df.timestamp.min()).days} days)")
    add(f"- Distinct nodes: **{df.node.nunique():,}**; racks: {df.rack.nunique()}; node cards: {df.nodecard.nunique():,}")
    add(f"- Alert lines: **{df.is_alert.sum():,}** ({df.is_alert.mean():.2%})")
    add(f"- Distinct alert categories: **{df.loc[df.is_alert, 'alert_tag'].nunique()}**\n")

    # 1. volume per day
    per_day = df.set_index("timestamp").resample("1D").size()
    fig, ax = plt.subplots(figsize=(10, 3))
    per_day.plot(ax=ax); ax.set_ylabel("lines/day"); ax.set_title("Log volume per day")
    _save(fig, "eda_01_volume_per_day.png")
    add(f"## Volume per day\n![](figures/eda_01_volume_per_day{SUFFIX}.png)\n")
    add(f"Median {per_day.median():,.0f} lines/day; max {per_day.max():,.0f}; "
        f"{(per_day == 0).sum()} days with no lines.\n")

    # 2. lines per node
    per_node = df.groupby("node", observed=True).size().sort_values(ascending=False)
    fig, ax = plt.subplots(figsize=(6, 3.5))
    ax.hist(np.log10(per_node.values), bins=40); ax.set_xlabel("log10(lines per node)"); ax.set_ylabel("nodes")
    ax.set_title("Lines per node")
    _save(fig, "eda_02_lines_per_node.png")
    add(f"## Lines per node\n![](figures/eda_02_lines_per_node{SUFFIX}.png)\n")
    add(f"Top 1% of nodes produce {per_node.head(max(1, len(per_node)//100)).sum() / len(df):.1%} of all lines.\n")

    # 3. alert categories
    cats = df.loc[df.is_alert, "alert_tag"].value_counts()
    fig, ax = plt.subplots(figsize=(8, 5))
    cats.head(25).plot.barh(ax=ax); ax.invert_yaxis(); ax.set_xscale("log"); ax.set_title("Alert categories (top 25, log scale)")
    _save(fig, "eda_03_alert_categories.png")
    add(f"## Alert categories\n![](figures/eda_03_alert_categories{SUFFIX}.png)\n")
    add(cats.to_frame("lines").to_markdown() + "\n")

    # 4. category × component × level cross-tab (needed for the failure definition)
    ct = (df[df.is_alert].groupby(["alert_tag", "component", "level"], observed=True).size()
          .reset_index(name="lines").sort_values("lines", ascending=False))
    ct.to_csv(RESULTS / "eda_alert_component_level.csv", index=False)
    add("## Alert category × component × level\n")
    add("Saved to `results/eda_alert_component_level.csv`. Top 30 rows:\n")
    add(ct.head(30).to_markdown(index=False) + "\n")
    lvl = df.level.value_counts()
    add("Level counts over all lines:\n\n" + lvl.to_frame("lines").to_markdown() + "\n")

    # 5. burstiness: gap between consecutive alert lines on the same node
    al = df[df.is_alert].sort_values(["node", "timestamp"])
    gaps = al.groupby("node", observed=True)["timestamp"].diff().dt.total_seconds().dropna()
    fig, ax = plt.subplots(figsize=(6, 3.5))
    ax.hist(np.log10(gaps[gaps > 0].values + 1e-3), bins=50)
    ax.set_xlabel("log10(seconds between consecutive alerts on same node)"); ax.set_ylabel("count")
    ax.set_title("Alert burstiness")
    _save(fig, "eda_04_alert_gaps.png")
    add(f"## Burstiness of alerts\n![](figures/eda_04_alert_gaps{SUFFIX}.png)\n")
    add(f"{(gaps <= 1).mean():.1%} of consecutive same-node alerts are ≤1 s apart; "
        f"{(gaps <= 60).mean():.1%} are ≤60 s apart; median gap {gaps.median():.0f} s.\n")

    # 6. duplicate consecutive lines on same node
    df["prev_msg_same"] = (df.groupby("node", observed=True)["message"].shift() == df["message"])
    add(f"## Repeated lines\n{df.prev_msg_same.mean():.1%} of lines repeat the previous message on the same node.\n")

    # 7. top messages
    top_msgs = df["message"].value_counts().head(30)
    add("## Top 30 raw messages\n" + top_msgs.to_frame("lines").to_markdown() + "\n")

    # 8. hour-of-day and weekday profile (confounder evidence)
    # BGL ran at LLNL (California). Epochs are UTC; convert to local time so "night" means night.
    local = df.timestamp.dt.tz_convert("America/Los_Angeles")
    hod = df.groupby(local.dt.hour).size()
    hod_alert = df[df.is_alert].groupby(local[df.is_alert].dt.hour).size()
    fig, ax = plt.subplots(1, 2, figsize=(10, 3))
    hod.plot.bar(ax=ax[0]); ax[0].set_title("All lines by local hour (US/Pacific)")
    hod_alert.plot.bar(ax=ax[1], color="C3"); ax[1].set_title("Alert lines by local hour (US/Pacific)")
    _save(fig, "eda_05_hour_of_day.png")
    add(f"## Hour-of-day profile\n![](figures/eda_05_hour_of_day{SUFFIX}.png)\n")

    add("## Three findings that constrain modelling\n")
    add("This file is regenerated on every run. The findings are written and maintained in `the report (Question 1, findings)`.\n")

    print(f"[eda] figures → {FIG}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sample", action="store_true")
    args = ap.parse_args()
    global SUFFIX
    SUFFIX = "_sample" if args.sample else ""
    pq_path = DATA_INTERIM / ("bgl_parsed_sample.parquet" if args.sample else "bgl_parsed.parquet")
    run(pq_path)


if __name__ == "__main__":
    main()
